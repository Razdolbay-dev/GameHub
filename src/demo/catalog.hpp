#include <iterator>
#include <cstddef>
#include <cstdint>
#include <span>
#include <vector>

namespace hui::gfx
{
class Renderer;
}

namespace hui::demo
{

// One made-up title. Nothing here refers to a real product: the names,
// studios and numbers exist only to give the designs something to show.
struct Item
{
    const char *title;
    const char *studio;
    const char *genre;
    const char *blurb;
    int year;
    float rating;      // 0..5
    float progress;    // 0..1 of the story
    int hours;         // time played
    int players;       // local players supported
    gfx::Color dark;   // palette: the deepest tone of the cover
    gfx::Color mid;    // its body colour
    gfx::Color accent; // the colour a design may pick up as highlight
    // Square cover art, rendered at start-up. Draw it with
    // list.image(item.cover, rect, gfx::kCanvasUv, tint, radius).
    std::uint32_t cover = 0;
    // True when `cover` was generated by build_covers() and must be freed by
    // release_covers(). Posters uploaded by the app set cover but leave this
    // false, so release_covers() does not delete them.
    bool owned_cover = false;
};

class Catalog
{
  public:
    Catalog();
    Catalog(const Catalog &) = delete;
    Catalog &operator=(const Catalog &) = delete;

    bool build_covers(gfx::Renderer &renderer, const ui::Fonts &fonts);
    void release_covers();

    // Replace the built-in demo seeds with caller-provided items.
    // Use before build_covers() so covers are generated for the new data.
    void set_items(std::vector<Item> items)
    {
        items_ = std::move(items);
    }

    // Append items without touching the ones already present. Cover textures
    // for the new items are generated by the next build_covers() call.
    void append_items(std::vector<Item> items)
    {
        items_.insert(items_.end(), std::make_move_iterator(items.begin()),
                      std::make_move_iterator(items.end()));
    }

    std::span<const Item> items() const
    {
        return items_;
    }
    std::size_t size() const
    {
        return items_.size();
    }
    const Item &operator[](std::size_t index) const
    {
        return items_[index % items_.size()];
    }

    static constexpr int kCoverSize = 512;

  private:
    std::vector<Item> items_;
};

} // namespace hui::demo
